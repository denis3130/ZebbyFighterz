#!/usr/bin/env python3
"""Builds play/: the installable phone version of the game (GitHub Pages, "Aggiungi alla schermata Home").

play/index.html      = index.html as a full document: charset, viewport, home-screen metas, manifest, three.js
                       inlined (no CDN: it works offline) and the service worker registration.
play/manifest.webmanifest, play/sw.js (caches the page for offline play), play/icon-180/192/512.png (Ren's face).

Run by mk.sh after index.html is built. Usage: python3 tools/make_play.py
"""
import hashlib, json, os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'play')
CDN = '<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>'
DARK, ORANGE = '#14121c', '#ff7a1a'

HEAD = ('<!doctype html><html lang="it"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">'
        '<meta name="theme-color" content="' + DARK + '">'
        '<meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-capable" content="yes">'
        '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">'
        '<meta name="apple-mobile-web-app-title" content="Voidrise">'
        '<link rel="manifest" href="manifest.webmanifest"><link rel="apple-touch-icon" href="icon-180.png">'
        '<link rel="icon" type="image/png" href="icon-192.png"></head><body>')
# The service worker only where it can run (https or localhost); a failure leaves the game working online.
REGISTER = ("<script>if('serviceWorker' in navigator)addEventListener('load',function(){"
            "navigator.serviceWorker.register('sw.js').catch(function(){});});</script>")

MANIFEST = {
    'name': 'Voidrise Fighters', 'short_name': 'Voidrise', 'lang': 'it',
    'start_url': './', 'scope': './', 'display': 'fullscreen', 'display_override': ['fullscreen', 'standalone'],
    'orientation': 'landscape', 'background_color': DARK, 'theme_color': DARK,
    'icons': [{'src': 'icon-192.png', 'sizes': '192x192', 'type': 'image/png'},
              {'src': 'icon-512.png', 'sizes': '512x512', 'type': 'image/png'},
              {'src': 'icon-512.png', 'sizes': '512x512', 'type': 'image/png', 'purpose': 'maskable'}],
}

# Cache-first for the game's own files (a new build has a new cache name, so the old one is dropped); the Google Fonts
# are kept once seen, so the titles keep their font offline too. Everything else goes to the network.
SW = """// Voidrise Fighters service worker (generated by tools/make_play.py): offline play once the page has opened.
const CACHE = 'voidrise-%(ver)s', FILES = ['./', './index.html', './manifest.webmanifest', './icon-180.png', './icon-192.png', './icon-512.png'];
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('voidrise-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET') return;
  if (u.origin === location.origin || /fonts\\.(googleapis|gstatic)\\.com$/.test(u.hostname)) {
    e.respondWith(caches.open(CACHE).then(c => c.match(e.request, {ignoreSearch: u.origin === location.origin}).then(hit => hit ||
      fetch(e.request).then(r => { if (r.ok || r.type === 'opaque') c.put(e.request, r.clone()); return r; }))));
  }
});
"""


def icon(size):
    """Ren's face from Denis's character sheet, with the game's orange slash in the corner (iOS rounds the corners)."""
    face = Image.open(os.path.join(ROOT, 'docs', 'ref', 'personaggi', 'ren.png')).convert('RGB').crop((352, 18, 672, 338))
    im = face.resize((size, size), Image.LANCZOS)
    d, s = ImageDraw.Draw(im), size / 100
    d.polygon([(70 * s, 100 * s), (84 * s, 100 * s), (100 * s, 72 * s), (100 * s, 58 * s)], fill=ORANGE)
    return im


def main():
    os.makedirs(OUT, exist_ok=True)
    page = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()
    three = open(os.path.join(ROOT, 'three.min.js'), encoding='utf-8').read()
    assert page.count(CDN) == 1 and '</script' not in three and 'window.__VF=' not in page
    html = HEAD + page.replace(CDN, '<script>\n' + three + '\n</script>') + REGISTER + '</body></html>'
    open(os.path.join(OUT, 'index.html'), 'w', encoding='utf-8').write(html)
    open(os.path.join(OUT, 'manifest.webmanifest'), 'w', encoding='utf-8').write(json.dumps(MANIFEST, ensure_ascii=False, indent=1) + '\n')
    for n in (180, 192, 512):
        icon(n).save(os.path.join(OUT, 'icon-%d.png' % n), optimize=True)
    ver = hashlib.sha256(html.encode('utf-8')).hexdigest()[:12]
    open(os.path.join(OUT, 'sw.js'), 'w', encoding='utf-8').write(SW % {'ver': ver})
    print('play', len(html), ver)


if __name__ == '__main__':
    main()
